        // ============================================================
        //  运行时表：静态构造里从上面两张表展开
        // ============================================================

        private static readonly Dictionary<char, char> C2T = new Dictionary<char, char>();
        private static readonly Dictionary<char, char> T2C = new Dictionary<char, char>();
        private static string[] _phraseSimp;
        private static string[] _phraseTrad;
        private static Dictionary<char, int[]> _idxSimp;   // 简体词首字 -> 词表下标（长词在前）
        private static Dictionary<char, int[]> _idxTrad;   // 繁体词首字 -> 词表下标（长词在前）

        static ZhConvert()
        {
            // 1) 字表展开。长度取短的那个（真出现长度不等也不会越界，只是尾部不生效）。
            int n = Simp.Length < Trad.Length ? Simp.Length : Trad.Length;
            for (int i = 0; i < n; i++)
            {
                char s = Simp[i];
                char t = Trad[i];
                if (s == t) continue;                     // 本来就一样的字不入表
                if (!C2T.ContainsKey(s)) C2T[s] = t;       // 同一简体字只认第一条，结果确定
                if (!T2C.ContainsKey(t)) T2C[t] = s;       // 多对一：先到先得，先来的赢
            }

            // 2) 词表展开 + 按词长倒序（插入排序，稳定；表很小，几毫秒）
            int m = Phrases.GetLength(0);
            _phraseSimp = new string[m];
            _phraseTrad = new string[m];
            for (int i = 0; i < m; i++)
            {
                _phraseSimp[i] = Phrases[i, 0];
                _phraseTrad[i] = Phrases[i, 1];
            }
            for (int i = 1; i < m; i++)
            {
                string ks = _phraseSimp[i];
                string kt = _phraseTrad[i];
                int j = i - 1;
                while (j >= 0 && _phraseSimp[j].Length < ks.Length)
                {
                    _phraseSimp[j + 1] = _phraseSimp[j];
                    _phraseTrad[j + 1] = _phraseTrad[j];
                    j--;
                }
                _phraseSimp[j + 1] = ks;
                _phraseTrad[j + 1] = kt;
            }

            // 3) 用词表里出现的"繁体专有字"补反查表（髮→发、隻→只、臺→台、鬆→松、
            //    乾→干、麵→面…）。已有的不覆盖：先到先得，保证反查稳定。
            //    只补繁体侧，不补简体侧 —— 简体侧的字不能因为词表就变成繁体字。
            for (int i = 0; i < m; i++)
            {
                string ks = _phraseSimp[i];
                string kt = _phraseTrad[i];
                int len = ks.Length < kt.Length ? ks.Length : kt.Length;
                for (int k = 0; k < len; k++)
                {
                    if (kt[k] == ks[k]) continue;
                    if (!T2C.ContainsKey(kt[k])) T2C[kt[k]] = ks[k];
                }
            }

            // 4) 首字索引：绝大多数位置首字不在词表里，一次查字典就跳过，
            //    10 MB 正文也不会退化成"每个字都比一遍词表"。
            _idxSimp = BuildIndex(_phraseSimp);
            _idxTrad = BuildIndex(_phraseTrad);
        }

        /// <summary>把词表按首字建索引（词表已按长度倒序，所以下标顺序就是优先级）</summary>
        private static Dictionary<char, int[]> BuildIndex(string[] keys)
        {
            var tmp = new Dictionary<char, List<int>>();
            for (int i = 0; i < keys.Length; i++)
            {
                if (keys[i] == null || keys[i].Length == 0) continue;
                char c = keys[i][0];
                List<int> lst;
                if (!tmp.TryGetValue(c, out lst))
                {
                    lst = new List<int>();
                    tmp[c] = lst;
                }
                lst.Add(i);
            }
            var res = new Dictionary<char, int[]>();
            foreach (var kv in tmp) res[kv.Key] = kv.Value.ToArray();
            return res;
        }

        // ============================================================
        //  公开 API
        // ============================================================

        /// <summary>简体 → 繁体；null / 空串原样返回。表里没有的字原样透传。</summary>
        public static string ToTraditional(string s)
        {
            return Translate(s, C2T, _phraseSimp, _phraseTrad, _idxSimp);
        }

        /// <summary>繁体 → 简体；null / 空串原样返回。多对一时按字表顺序先到先得。</summary>
        public static string ToSimplified(string s)
        {
            return Translate(s, T2C, _phraseTrad, _phraseSimp, _idxTrad);
        }

        /// <summary>
        /// 是否含"繁体专有字"（只用于界面提示 / 自动判断，不做严格判定）。
        /// null / 空串返回 false。
        /// </summary>
        public static bool LooksTraditional(string s)
        {
            if (string.IsNullOrEmpty(s)) return false;
            for (int i = 0; i < s.Length; i++)
                if (IsTradOnly(s[i])) return true;
            return false;
        }

        /// <summary>
        /// 按样本统计判断语种：繁体专有字多 → "zh-TW"，否则 → "zh-CN"。
        /// 空 / 纯空白 / 完全没有可比字（数字、英文）都返回 "zh-CN"。
        /// O(n)、不分配。
        /// </summary>
        public static string DetectScript(string s)
        {
            if (string.IsNullOrEmpty(s)) return "zh-CN";
            int trad = 0;
            int simp = 0;
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                bool isTrad = T2C.ContainsKey(c);
                bool isSimp = C2T.ContainsKey(c);
                if (isTrad && !isSimp) trad++;
                else if (isSimp && !isTrad) simp++;
            }
            return trad > simp ? "zh-TW" : "zh-CN";
        }

        // ============================================================
        //  内部实现
        // ============================================================

        /// <summary>繁体专有字：反查表里有、正查表里没有</summary>
        private static bool IsTradOnly(char c)
        {
            return T2C.ContainsKey(c) && !C2T.ContainsKey(c);
        }

        /// <summary>
        /// 通用的逐字转换：
        ///   先按词表（长词优先）匹配，命中就整段替换并跳过，替换结果不再回扫；
        ///   没命中才走字表，字表没有就原样抄一个字。
        /// </summary>
        private static string Translate(string s, Dictionary<char, char> map,
                                        string[] from, string[] to, Dictionary<char, int[]> index)
        {
            if (string.IsNullOrEmpty(s)) return s;
            var sb = new StringBuilder(s.Length + 8);
            int i = 0;
            while (i < s.Length)
            {
                int[] cands;
                if (index.TryGetValue(s[i], out cands))
                {
                    bool hit = false;
                    for (int p = 0; p < cands.Length; p++)
                    {
                        int pi = cands[p];
                        string key = from[pi];
                        if (key.Length == 0 || i + key.Length > s.Length) continue;
                        if (string.CompareOrdinal(s, i, key, 0, key.Length) != 0) continue;
                        sb.Append(to[pi]);
                        i += key.Length;
                        hit = true;
                        break;
                    }
                    if (hit) continue;
                }
                char c = s[i];
                char r;
                if (map.TryGetValue(c, out r)) sb.Append(r);
                else sb.Append(c);
                i++;
            }
            return sb.ToString();
        }
